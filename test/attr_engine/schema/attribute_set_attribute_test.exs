defmodule AttrEngine.Schema.AttributeSetAttributeTest do
  use ExUnit.Case, async: true

  alias AttrEngine.Schema.AttributeSetAttribute, as: ASA

  describe "schema" do
    test "has surrogate :id primary key" do
      assert ASA.__schema__(:primary_key) == [:id]
    end

    test "id field is autogenerated bigserial" do
      assert {:id, :id} == ASA.__schema__(:type, :id) |> then(fn t -> {:id, t} end)
    end

    test "handle is a regular field" do
      fields = ASA.__schema__(:fields)
      assert :handle in fields
    end

    test "belongs_to associations exist without primary_key flag" do
      assocs = ASA.__schema__(:associations)
      assert :attribute_set in assocs
      assert :attribute in assocs
    end
  end

  describe "changeset — multi-handle support" do
    test "two ASAs with same (set, attr) but different handles produce valid changesets" do
      cs1 =
        ASA.changeset(%ASA{}, %{
          handle: "first_name",
          attribute_set_id: 1,
          attribute_id: 42
        })

      cs2 =
        ASA.changeset(%ASA{}, %{
          handle: "last_name",
          attribute_set_id: 1,
          attribute_id: 42
        })

      assert cs1.valid?
      assert cs2.valid?
      assert Ecto.Changeset.get_field(cs1, :handle) == "first_name"
      assert Ecto.Changeset.get_field(cs2, :handle) == "last_name"
      assert Ecto.Changeset.get_field(cs1, :attribute_id) == Ecto.Changeset.get_field(cs2, :attribute_id)
    end

    test "handle is required" do
      cs = ASA.changeset(%ASA{}, %{attribute_set_id: 1, attribute_id: 42})
      refute cs.valid?
      assert Keyword.has_key?(cs.errors, :handle)
    end

    test "empty string handle is rejected" do
      cs = ASA.changeset(%ASA{}, %{handle: "", attribute_set_id: 1, attribute_id: 42})
      refute cs.valid?
      assert Keyword.has_key?(cs.errors, :handle)
    end

    test "whitespace-only handle is rejected" do
      cs = ASA.changeset(%ASA{}, %{handle: "   ", attribute_set_id: 1, attribute_id: 42})
      refute cs.valid?
      assert Keyword.has_key?(cs.errors, :handle)
    end

    test "changeset declares unique_constraint on (set, handle)" do
      cs = ASA.changeset(%ASA{}, %{handle: "title", attribute_set_id: 1, attribute_id: 42})

      # Simulate a DB unique violation
      {:error, cs_with_error} =
        Ecto.Changeset.apply_action(
          Ecto.Changeset.add_error(cs, :attribute_set_id, "handle already exists in this attribute set"),
          :insert
        )

      assert Keyword.has_key?(cs_with_error.errors, :attribute_set_id)
    end
  end

  describe "cascade contract — multi-ASA per primitive" do
    test "resolve_attrs_meta returns distinct entries for ASAs sharing an attribute_id" do
      # This is the schema-level proof that the Cascade output structure
      # supports multiple ASAs per primitive. The actual DB-level test
      # lives in the consumer's test suite.
      #
      # Given two ASA structs with same attribute_id but different handles/sorts:
      asa1 = %ASA{handle: "first_name", attribute_id: 42, attribute_set_id: 1, sort: 0}
      asa2 = %ASA{handle: "last_name", attribute_id: 42, attribute_set_id: 1, sort: 1}

      # They are distinct structs that would produce distinct rows
      refute asa1.handle == asa2.handle
      assert asa1.attribute_id == asa2.attribute_id
      assert asa1.sort < asa2.sort
    end
  end
end
